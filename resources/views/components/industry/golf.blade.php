    <p class="eye">The Golf Course Challenge</p>
    <h2 class="sh">Three water problems every golf course<br><em>carries — and almost none have addressed.</em></h2>
    <p class="sub">Golf course water management is dominated by irrigation — but billing errors and well/municipal blend inefficiency create significant additional cost exposure that most operators have never quantified.</p>
  </div>
  <div class="prob-grid"><div class="prob-card">
      <div class="prob-num">01</div>
      <div class="prob-title">Irrigation system programmed on time-based schedules set at installation — never updated</div>
      <p class="prob-body">Most golf course irrigation systems are running on time-based schedules programmed during installation or last renovation — schedules that don't account for seasonal variation, local ET rates, soil moisture conditions, or recent precipitation. An 18-hole course with 500+ irrigation heads running on a 1998 schedule in a Florida climate can be applying 30&ndash;50% more water than turf conditions require. The water is paid for, but it doesn't improve playing conditions — it just leaves the property through runoff or evaporation.</p>
    </div><div class="prob-card">
      <div class="prob-num">02</div>
      <div class="prob-title">Well/municipal blend ratio not optimised — well costs not benchmarked against municipal rates</div>
      <p class="prob-body">Golf courses that have both a well and a municipal water connection frequently run them at a blend ratio that was set historically rather than economically. Well operating costs (electricity, maintenance, treatment) are often higher than assumed when the blend ratio is calculated against municipal water rates. Without a current-year cost comparison, courses may be paying more for well water than they would for municipal supply — or vice versa — and running the more expensive source at a higher share than the economics justify.</p>
    </div><div class="prob-card">
      <div class="prob-num">03</div>
      <div class="prob-title">Irrigation runoff and overwatering creating regulatory exposure alongside cost waste</div>
      <p class="prob-body">In Florida, California, and other water-constrained states, golf courses are under increasing regulatory scrutiny for irrigation runoff volumes and application rates. Over-irrigation doesn't just waste water and money — it creates regulatory risk in jurisdictions where water use permits specify maximum application rates. WST's irrigation audit documents current application rates against permit conditions, identifying both the cost saving and the compliance improvement from moving to ET-based scheduling.</p>
    </div></div>
