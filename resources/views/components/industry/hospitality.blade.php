<section class="sec sec-o">
  <div style="max-width:760px; margin-bottom:40px;">
    <p class="eye">The Hospitality Challenge</p>
    <h2 class="sh">Hotels carry more water cost exposure<br><em>than almost any other asset class.</em></h2>
    <p class="sub">The hospitality sector's water intensity is driven by guest services, mechanical systems, and 24-hour operations &mdash; each creating distinct categories of billing risk and waste that most hotel operators have never systematically addressed.</p>
  </div>
  <div class="prob-grid">
    <div class="prob-card">
      <div class="prob-num">01</div>
      <div class="prob-title">Cooling tower waste &mdash; the single largest controllable water cost</div>
      <p class="prob-body">Cooling towers in full-service hotels can account for 25&ndash;35% of total water consumption. Bleed rates set too low or too high, makeup water overflows, and drift eliminators in poor condition all waste water invisibly. Most engineering teams have never had a baseline reading on their cooling tower water use &mdash; let alone a target bleed rate optimised for local water chemistry.</p>
    </div>
    <div class="prob-card">
      <div class="prob-num">02</div>
      <div class="prob-title">Sewer mismatch on pool &amp; laundry make-up water</div>
      <p class="prob-body">Most municipalities charge sewer fees on total water consumption &mdash; but water used in pools, cooling towers, and irrigation never enters the sewer. Hotels that don't file for sewer discharge exemptions or sub-meter make-up water pay sewer charges on water that never leaves the property. This is one of the most common billing errors WST finds in hotel audits, averaging $18,000&ndash;$45,000 per year in recoverable overcharges per property.</p>
    </div>
    <div class="prob-card">
      <div class="prob-num">03</div>
      <div class="prob-title">GRESB water scores below peer average despite genuine improvements</div>
      <p class="prob-body">Hotel REITs averaged a 67.7% water indicator score in GRESB 2025 &mdash; the second-lowest performance indicator in the sector. Most of that gap is not a performance problem. It is a data coverage and documentation problem. Properties that have made genuine water efficiency improvements often lack the verified consumption data and GRESB-formatted evidence needed for the WT1 indicator. The work exists. The documentation doesn't.</p>
    </div>
  </div>
</section>

