    <p class="eye">The Industrial Challenge</p>
    <h2 class="sh">Manufacturing facilities carry water cost<br><em>exposure across every production system.</em></h2>
    <p class="sub">Industrial water management is not a single-system problem. Process cooling, boiler feed, product washing, and sanitation all operate on different water quality requirements, different tariff classifications, and different discharge profiles — creating billing complexity that most engineering teams manage reactively rather than systematically.</p>
  </div>
  <div class="prob-grid"><div class="prob-card">
      <div class="prob-num">01</div>
      <div class="prob-title">Process cooling systems running at conservative bleed rates — wasting millions of gallons</div>
      <p class="prob-body">Industrial cooling towers and heat exchangers serving process equipment are almost always running at conservative bleed rates set for worst-case water chemistry. Unlike commercial HVAC towers, process cooling systems often run at higher temperatures and loads, making bleed rate optimisation both more impactful and more technically demanding. A process cooling system consuming 50 million gallons per year running 10% above the optimal bleed rate is wasting 5 million gallons annually — $25,000&ndash;$75,000 depending on local water rates and discharge charges.</p>
    </div><div class="prob-card">
      <div class="prob-num">02</div>
      <div class="prob-title">Industrial discharge permits and sewer surcharge classifications often incorrect</div>
      <p class="prob-body">Manufacturing facilities in most US jurisdictions are subject to industrial pretreatment regulations and tiered sewer surcharge rates based on effluent characteristics (BOD, TSS, FOG). Misclassification of discharge type — billing at higher surcharge rates than the effluent actually warrants — is common and rarely audited by the facility. WST's billing review cross-references discharge permit conditions against actual utility invoices, identifying misclassifications that have often persisted for multiple years.</p>
    </div><div class="prob-card">
      <div class="prob-num">03</div>
      <div class="prob-title">Water recycling and reclaim opportunities identified but never quantified</div>
      <p class="prob-body">Most manufacturing facilities have visible water recycling opportunities — cooling water recirculation, process rinse water reuse, condensate recovery from steam systems — that engineering teams are aware of but have never formally quantified. Without a quantified ROI analysis, these projects remain on the backlog indefinitely. WST quantifies the savings, documents the payback, and formats the case for capital committee presentation.</p>
    </div></div>
