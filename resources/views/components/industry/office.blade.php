    <p class="eye">The Office Challenge</p>
    <h2 class="sh">Three water problems that Class A office<br><em>buildings carry silently.</em></h2>
    <p class="sub">Office buildings are not high-drama water users. The problems are structural and billing-related rather than operational — which is exactly why they persist for years without being addressed.</p>
  </div>
  <div class="prob-grid"><div class="prob-card">
      <div class="prob-num">01</div>
      <div class="prob-title">HVAC and cooling tower water not sub-metered — sewer charges applied to all of it</div>
      <p class="prob-body">Centralised chilled water plants serving multi-tenant office buildings discharge cooling tower bleed water but the make-up volume feeding the towers is rarely sub-metered. Without a dedicated make-up meter, the property pays sewer charges on all water consumed — including the significant volume that evaporates through the cooling towers and never enters the sewer. In a 300,000 sq ft Class A building running chillers year-round, this can represent $20,000&ndash;$45,000 in annual sewer overcharges.</p>
    </div><div class="prob-card">
      <div class="prob-num">02</div>
      <div class="prob-title">Tenant sub-metering mismatches generating billing disputes and unrecovered cost</div>
      <p class="prob-body">Multi-tenant buildings with individual tenant sub-meters frequently develop discrepancies between the master utility meter and the sum of sub-meter readings — a gap that represents water consumed in common areas, mechanical rooms, and restrooms that isn't being allocated to any billing account. Over time, this gap compounds into unrecovered operating cost for the landlord. On a 20-tenant building, the common area water cost gap is often 8&ndash;15% of the total annual water bill.</p>
    </div><div class="prob-card">
      <div class="prob-num">03</div>
      <div class="prob-title">No verified consumption data for GRESB WT1 — suppressing ESG scores for listed office REITs</div>
      <p class="prob-body">Office REITs participating in GRESB frequently struggle with WT1 data coverage because utility bill collection across multi-tenant buildings with utility-paid leases is fragmented. Tenants who pay their own utility bills don't share data with the landlord. Without Ara AI's automated collection, the landlord cannot submit verified whole-building consumption data for WT1 — scoring lower than the building's actual water management performance warrants.</p>
    </div></div>
